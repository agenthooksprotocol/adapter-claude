// Bundle the adapter and the AHP SDK into the one hooks module a Claude Code
// mod loads. The module runs with no Node and no code generation, so:
// - node: builtins resolve to stubs (the adapter injects a launcher, fetch and
//   resolvers, so the Node paths never run),
// - no `import()` may remain anywhere in the output (a module holding one does
//   not load), and
// - the result is checked for both before it is written.
import { build } from "esbuild";
import { readdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const hooksDir = join(root, "plugin/hooks");
const outfile = join(hooksDir, "register.js");
// Claude Code reads no hooks-module file over 1 MiB.
const FILE_LIMIT = 1024 * 1024;
const minify = !process.argv.includes("--no-minify");

// The SDK's precompiled validators come as shards, each its own file here.
const sdkRoot = dirname(createRequire(import.meta.url).resolve("agenthooksprotocol/client").replace(/\/client\/index\.js$/, "/client"));
const shardDir = join(sdkRoot, "draft/validators");
const shards = readdirSync(shardDir).filter((name) => /^part-\d+\.js$/.test(name));

/** Keep shard imports as relative imports of the shard files. */
const shardImports = (prefix) => ({
  name: "validator-shards",
  setup(build) {
    build.onResolve({ filter: /^\.\/part-\d+\.js$/ }, (args) =>
      args.importer.includes("/draft/validators/") && args.kind !== "entry-point"
        ? { path: prefix + args.path.slice(2), external: true }
        : undefined);
  },
});

const stubs = {
  "node:child_process": `export function spawn() { throw new Error("node:child_process is unavailable in a Claude Code mod"); }`,
  "node:diagnostics_channel": `export function channel() { return { hasSubscribers: false, publish() {} }; }`,
};

/** Node builtins become stubs; any other node: import is an error. */
const nodeBuiltins = {
  name: "node-builtins",
  setup(build) {
    build.onResolve({ filter: /^node:/ }, (args) => {
      if (!(args.path in stubs))
        return { errors: [{ text: `${args.path} has no stub (imported by ${args.importer})` }] };
      return { path: args.path, namespace: "node-stub" };
    });
    build.onLoad({ filter: /.*/, namespace: "node-stub" }, (args) => ({
      contents: stubs[args.path],
      loader: "js",
    }));
  },
};

/** The SDK reaches Node-only modules through `import(variable)` on paths the
 * adapter never takes (it injects `resolveHostname` and `fetch`). Replace them
 * with a rejection so the bundle holds no dynamic import. */
const noDynamicImport = {
  name: "no-dynamic-import",
  setup(build) {
    build.onLoad({ filter: /agenthooksprotocol\/.*\/dist\/src\/.*\.js$|packages\/sdk\/dist\/src\/.*\.js$/ }, (args) => {
      const source = readFileSync(args.path, "utf8");
      if (!source.includes("import(")) return undefined;
      return {
        contents: source.replace(
          /\bimport\((\w+)\)/g,
          (_match, name) => `Promise.reject(new Error("dynamic import of " + ${name} + " is unavailable in a Claude Code mod"))`,
        ),
        loader: "js",
      };
    });
  },
};

await build({
  entryPoints: [join(root, "src/register.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  conditions: ["import", "default"],
  // `claude plugin validate` reads the module's source: `register`, `on` and
  // `$` must keep their names, so identifiers are never mangled here.
  minifyWhitespace: minify,
  minifySyntax: minify,
  legalComments: "none",
  plugins: [nodeBuiltins, noDynamicImport, shardImports("./validators/")],
  logLevel: "warning",
  banner: {
    js: "// Generated by scripts/build.mjs from src/. DO NOT EDIT.",
  },
});

rmSync(join(hooksDir, "validators"), { recursive: true, force: true });
for (const shard of shards) {
  await build({
    entryPoints: [join(shardDir, shard)],
    outfile: join(hooksDir, "validators", shard),
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    mainFields: ["module", "main"],
    minify,
    legalComments: "none",
    plugins: [shardImports("./")],
    logLevel: "warning",
  });
}

const files = [outfile, ...shards.map((shard) => join(hooksDir, "validators", shard))];
let failed = false;
for (const file of files) {
  const output = readFileSync(file, "utf8");
  const relative = file.slice(root.length + 1);
  const size = statSync(file).size;
  if (size > FILE_LIMIT) {
    console.error(`${relative}: ${size} bytes is over Claude Code's 1 MiB module limit`);
    failed = true;
  }
  if (/\bimport\s*\(/.test(output)) {
    console.error(`${relative} holds a dynamic import (the module would not load)`);
    failed = true;
  }
  for (const match of output.matchAll(/(?:^|[;\n])\s*import\s[^;]*?from\s*"([^"]+)"/g))
    if (!match[1].startsWith("./")) {
      console.error(`${relative} imports ${match[1]}: the bundle must be self-contained`);
      failed = true;
    }
  console.log(`${relative}: ${(size / 1024).toFixed(0)} KiB`);
}
if (failed) process.exit(1);
